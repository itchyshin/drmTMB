test_that("cmr_data validates and preserves CJS conditioning metadata", {
  y <- rbind(c(1, 0, 1, 0), c(0, 1, 0, 0), c(0, 0, 0, 1))
  d <- cmr_data(y, id = c("a", "b", "c"), occasions = c(1, 2, 4, 7))
  expect_s3_class(d, "cmr_data")
  expect_identical(d$first, c(1L, 2L, 4L))
  expect_identical(d$end, c(4L, 4L, 4L))
  expect_equal(d$delta, matrix(c(1, 2, 3, 1, 2, 3, 1, 2, 3), 3, 3, byrow = TRUE))
  years <- cmr_data(y, occasions = c(1, 2, 4, 7), intervals = c(1, 2, 3), units = "years")
  expect_identical(years$units, "years")
  expect_equal(years$delta, d$delta)
  expect_error(cmr_data(y, units = 2), "character label")
  expect_error(cmr_data(rbind(c(0, 0), c(1, 0)), id = c("x", "x")), "unique")
  expect_error(cmr_data(rbind(c(0, 0), c(1, 0))), "all-zero")
})

test_that("masked encounters and administrative endpoints are explicit", {
  y <- rbind(c(1, NA, 0), c(0, 1, 0))
  obs <- rbind(c(TRUE, FALSE, TRUE), c(TRUE, TRUE, TRUE))
  d <- cmr_data(y, observed = obs, end = c(3, 3), intervals = c(2, 4))
  expect_identical(d$y[1, 2], 0L)
  expect_false(d$observed[1, 2])
  expect_equal(d$delta[1, ], c(2, 4))
  expect_error(cmr_data(y, observed = matrix(TRUE, 2, 3)), "observed encounter")
  expect_error(cmr_data(rbind(c(1, 0, 1), c(0, 1, 0)), end = c(2, 3)), "after")
})

test_that("keyed predictor joins preserve IDs containing separators", {
  y <- rbind(c(1, 0, 0), c(1, 0, 0))
  d <- cmr_data(y, id = c("a\rb", "a"))
  rows <- data.frame(i = c(1L, 2L), t = c(2L, 2L))
  x <- data.frame(id = c("a", "a\rb"), occasion = c(2, 2), z = c(20, 10))
  joined <- .cmr_join_predictors(d, x, rows, "p")
  expect_equal(joined$z, c(10, 20))
})
