# Profile deviance of the slant intercept from the skew-normal density written
# out by hand, independent of the TMB template and of drmTMB's profile code.
fix_1738_hand_deviance <- function(d, coefs) {
  X <- stats::model.matrix(~ x1 + x2 + f, d)
  nll <- function(par, nu) {
    sg <- exp(par[[6L]])
    z <- (d$y - X %*% par[1:5]) / sg
    -sum(log(2) - log(sg) + stats::dnorm(z, log = TRUE) +
      stats::pnorm(nu * z, log.p = TRUE))
  }
  ctrl <- list(reltol = 1e-14, maxit = 2000)
  best <- stats::optim(
    coefs[1:6], nll, nu = coefs[[7L]], method = "BFGS", control = ctrl
  )
  function(nu) {
    2 * (stats::optim(best$par, nll, nu = nu, method = "BFGS", control = ctrl)$value -
      best$value)
  }
}

test_that("#1738: skew-normal slant profile limits reach the 95% cutoff", {
  d <- fix_1738_data()
  fit <- drmTMB(bf(y ~ x1 + x2 + f, sigma ~ 1), family = skew_normal(), data = d)
  ci <- suppressWarnings(
    confint(fit, parm = "fixef:nu:(Intercept)", method = "profile")
  )
  expect_identical(ci$conf.status, "profile")

  # Exact limits from the hand-written profile in the issue (uniroot, tol 1e-8).
  expect_lt(abs(ci$lower - (-0.6261533)), 1e-3)
  expect_lt(abs(ci$upper - 3.16195), 1e-3)

  deviance <- fix_1738_hand_deviance(d, unlist(coef(fit)))
  cutoff <- stats::qchisq(0.95, df = 1)
  expect_lt(abs(deviance(ci$lower) - cutoff), 0.01)
  expect_lt(abs(deviance(ci$upper) - cutoff), 0.01)
})

test_that("#1738: endpoint refinement solves the cutoff between grid points", {
  # Convex profile objective 0.5 * t^4 on a coarse grid: the chord between
  # t = 1 and t = 2 crosses the cutoff well inside the true root.
  cutoff <- stats::qchisq(0.95, df = 1) / 2
  evaluator <- list(
    start_free = 0,
    evaluate = function(theta, start) list(nll = 0.5 * theta^4, par = start)
  )
  grid <- c(1, 2)
  excess <- 0.5 * grid^4 - cutoff
  chord <- stats::approx(excess, grid, xout = 0)$y
  refined <- drmTMB:::drm_tmbprofile_refine_endpoint(
    evaluator = evaluator,
    theta = grid,
    excess = excess,
    estimate = chord,
    nll_anchor = 0,
    cutoff = cutoff,
    root_tol = 1e-8
  )
  expect_lt(chord, (2 * cutoff)^0.25 - 0.1)
  expect_equal(refined, (2 * cutoff)^0.25, tolerance = 1e-6)

  # No sign change in the bracketing segment: keep the interpolated value.
  expect_identical(
    drmTMB:::drm_tmbprofile_refine_endpoint(
      evaluator = evaluator,
      theta = c(1, 2),
      excess = c(1, 2),
      estimate = 1.5,
      nll_anchor = 0,
      cutoff = cutoff,
      root_tol = 1e-8
    ),
    1.5
  )
})
