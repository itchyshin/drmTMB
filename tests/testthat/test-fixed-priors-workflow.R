test_that("prior workflow retains targets and guards unsupported inference", {
  set.seed(5105)
  d <- data.frame(x=rnorm(120))
  d$y <- 0.4 + 1.2*d$x + rnorm(120,sd=0.8)
  p <- drm_priors(drm_prior_normal("mu","all",sd=5,intercept="include"))
  f <- drmTMB(bf(mu=y~x,sigma=~1),data=d,priors=p)
  expect_equal(f$resolved_priors,drm_resolve_priors(f$formula,gaussian(),d,p))
  expect_identical(f$estimator,"MAP")
  expect_match(f$covariance_interpretation,"local_penalized")
  expect_lt(max(abs(unlist(coef(f,dpar="mu"))-c(0.4,1.2))),0.3)
  expect_equal(f$gradient-f$prior_gradient,f$likelihood_gradient,tolerance=1e-10)
  at <- list("fixef:mu:x"=0.7)
  beta <- coef(f,dpar="mu"); beta[["x"]]<-0.7
  s <- exp(coef(f,dpar="sigma")[[1]])
  expect_equal(objective_at(f,at),-sum(dnorm(d$y,as.vector(model.matrix(~x,d)%*%beta),s,log=TRUE)),tolerance=1e-8)
  expect_error(confint(f),"fixed-effect")
  expect_error(summary(f,conf.int=TRUE),"fixed-effect")
  expect_error(summary(f,conf.int=TRUE,method="profile"),"fixed-effect")
  expect_error(profile(f),"fixed-effect")
  expect_error(AIC(f),"fixed-effect")
  expect_error(BIC(f),"fixed-effect")
  expect_error(predict_parameters(f,conf.int=TRUE),"fixed-effect")
  expect_error(drm_lrtest(f,f),"MAP")
  u <- update(f)
  expect_equal(u$resolved_priors,f$resolved_priors)
  expect_equal(unlist(u$coefficients),unlist(f$coefficients),tolerance=1e-7)
  z <- drmTMB(f$formula,data=d,priors=drm_priors(drm_prior_ridge("mu","x",lambda=0)))
  plain <- drmTMB(f$formula,data=d)
  expect_identical(z$estimator,"ML")
  expect_equal(unlist(z$coefficients),unlist(plain$coefficients),tolerance=1e-7)
  expect_equal(z$fixed_prior_penalty,0)
})

test_that("bridge options preserve selectors and expected public columns", {
  p <- drm_priors(drm_prior_normal("mu","x",mean=0.3,sd=2),
                  drm_prior_ridge("sigma","all",lambda=0,intercept="include"))
  d <- data.frame(y=c(0,1,2,3),x=1:4)
  r <- drm_resolve_priors(bf(mu=y~x,sigma=~1),gaussian(),d,p)
  o <- drm_fixed_prior_bridge_options(p,r)
  expect_identical(o$priors[[1]],list(kind="normal",dpar="mu",coef="x",mean=0.3,sd=2))
  expect_identical(o$priors[[2]]$lambda,0)
  expect_identical(o$prior_expected[[2]],list(dpar="sigma",coef="(Intercept)"))
})

test_that("public selectors match fitted factor and no-intercept columns", {
  d <- data.frame(f=factor(rep(c("a","b","c"),each=4)),x=rep(c(-1,0,1,2),3))
  d$y <- rep(c(0.2,0.8,1.1),each=4)+0.4*d$x+rep(c(-0.1,0.2,-0.2,0.1),3)
  fm <- bf(mu=y~0+f+x,sigma=~1)
  p <- drm_priors(drm_prior_ridge("mu","all",lambda=0.2,intercept="exclude"))
  r <- drm_resolve_priors(fm,gaussian(),d,p)
  expect_identical(r$coefficient,colnames(model.matrix(~0+f+x,d)))
  fit <- drmTMB(fm,data=d,priors=p)
  expect_identical(fit$resolved_priors$coefficient,names(coef(fit,dpar="mu")))
  expect_true(all(is.finite(unlist(coef(fit)))))
  im <- bf(mu=y~f*x,sigma=~1)
  ip <- drm_priors(drm_prior_normal("mu","fb:x",sd=2))
  expect_identical(drm_resolve_priors(im,gaussian(),d,ip)$coefficient,"fb:x")
  expect_error(drmTMB(bf(mu=y~x+I(2*x)),data=d,priors=drm_priors(drm_prior_normal("mu","x",sd=1))),"rank|aliased")
  expect_error(drm_resolve_priors(bf(mu=y~x,sigma=~x+I(2*x)),gaussian(),d,
    drm_priors(drm_prior_normal("mu","x",sd=1))),"rank|aliased")
})

test_that("zero ridge preserves default likelihood controls", {
  p <- drm_priors(drm_prior_ridge("mu","x",lambda=0))
  expect_false(drm_fixed_priors_active(p))
  expect_true(drm_fixed_priors_active(drm_priors(drm_prior_normal("mu","x",sd=2))))
  d <- data.frame(x=1:6,y=c(1,2,2.5,4,4.8,6))
  z <- drmTMB(bf(y~x),data=d,priors=p)
  f <- drmTMB(bf(y~x),data=d)
  expect_identical(z$model$tmb_data$use_logsigma_clamp,f$model$tmb_data$use_logsigma_clamp)
  t <- f$opt$par;t[names(t)=="beta_sigma"] <- -20
  expect_equal(z$obj$fn(t),f$obj$fn(t),tolerance=0)
})
