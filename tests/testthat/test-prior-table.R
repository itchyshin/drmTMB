testthat::test_that('prior table fits match constructors and preserve the input', {
  d <- data.frame(y=c(.2,.8,.5,1.4,1,1.6,2,1.3,2.2,1.8,2.4,2.1),x=rep(c(-1,0,1),4),site=rep(letters[1:4],each=3),observer=rep(letters[5:7],4))
  f <- drmTMB::bf(mu=y~x+(1|site)+(1|observer),sigma=~1)
  table <- data.frame(prior=c('normal(0,2)','gamma(0.6666666666666666,2)'),class=c('fixef','ranef_sd'),coef=c('x',''))
  legacy <- drmTMB::drm_priors(drmTMB::drm_prior_normal('mu','x',sd=2),drmTMB::drm_prior_sd_gamma(group='site',shape=2,rate=3),drmTMB::drm_prior_sd_gamma(group='observer',shape=2,rate=3))
  a <- drmTMB::drmTMB(f,data=d,priors=table)
  b <- drmTMB::drmTMB(f,data=d,priors=legacy)
  testthat::expect_equal(a$opt$objective,b$opt$objective,tolerance=1e-9)
  testthat::expect_equal(a$obj$gr(a$opt$par),b$obj$gr(a$opt$par),tolerance=1e-8)
  testthat::expect_identical(attr(a$priors,'input_table'),table)
  testthat::expect_error(drmTMB::drmTMB(f,data=d,priors=table,weights=rep(2,nrow(d))), 'weight|unit')
  bad <- table; bad$prior[1] <- 'normal(1+1,2)'
  testthat::expect_error(drmTMB::drmTMB(f,data=d,priors=bad),'syntax')
})
testthat::test_that('update replays resolved prior targets', {
  d <- data.frame(y=c(.2,.8,.5,1.4,1,1.6,2,1.3),x=rep(c(-1,0,1,0),2),z=c(0,1,0,1,1,0,1,0))
  f <- drmTMB::bf(mu=y~x,sigma=~1)
  table <- data.frame(prior='normal(0,2)',class='fixef',coef='')
  fit <- drmTMB::drmTMB(f,data=d,priors=table)
  table$prior[1] <- 'not a prior'
  again <- update(fit,data=d)
  testthat::expect_equal(again$resolved_priors$coefficient,'x')
  testthat::expect_identical(attr(again$priors,'input_table')$prior,'normal(0,2)')
  restored <- unserialize(serialize(fit,NULL))
  restored_update <- update(restored,data=d)
  testthat::expect_equal(restored_update$resolved_priors$coefficient,'x')
  d$x <- factor(rep(c('a','b'),4))
  table$prior[1] <- 'normal(0,2)'
  factor_fit <- drmTMB::drmTMB(f,data=d,priors=table)
  d2 <- d; d2$x <- factor(rep(c('a','b','c','a'),2))
  changed <- update(factor_fit,data=d2)
  testthat::expect_equal(changed$resolved_priors$coefficient,'xb')

})
testthat::test_that('replay preserves interleaved prior target order', {
  d <- data.frame(y=c(.2,.8,.5,1.4,1,1.6,2,1.3,2.2,1.8,2.4,2.1),x=rep(c(-1,0,1),4),site=rep(letters[1:4],each=3),observer=rep(letters[5:7],4))
  f <- drmTMB::bf(mu=y~x+(1|site)+(1|observer),sigma=~1)
  p <- data.frame(prior=c('gamma(1,2)','normal(0,2)','gamma(1,3)'),class=c('ranef_sd','fixef','ranef_sd'),coef=c('site','x','observer'))
  fit <- drmTMB::drmTMB(f,data=d,priors=p)
  stored <- stats::getCall(fit)$priors
  labels <- vapply(stored,function(x) if (inherits(x,'drm_sd_prior')) x$group else x$coef,character(1))
  testthat::expect_identical(unname(labels),c('site','x','observer'))
})
testthat::test_that('broad fixed rule and explicit intercept are disjoint', {
  d <- data.frame(y=c(.2,.8,.5,1.4,1,1.6),x=c(-1,0,1,-1,0,1))
  f <- drmTMB::bf(mu=y~x,sigma=~1)
  p <- data.frame(prior=c('normal(0,2)','normal(1,3)'),class=c('fixef','fixef'),coef=c('','(Intercept)'))
  selected <- drmTMB::drm_resolve_priors(f,stats::gaussian(),d,p)
  testthat::expect_identical(selected$coefficient,c('x','(Intercept)'))
  fit <- drmTMB::drmTMB(f,data=d,priors=p)
  testthat::expect_identical(update(fit,data=d)$resolved_priors$coefficient,c('x','(Intercept)'))
})

testthat::test_that('zero ridge and fixed-only binomial tables match constructors', {
  d <- data.frame(y=c(.2,.8,.5,1.4,1,1.6,2,1.3,2.2,1.8,2.4,2.1),x=rep(c(-1,0,1),4))
  f <- bf(mu=y~x,sigma=~1)
  tab <- data.frame(prior='ridge(0)',class='fixef',coef='x')
  con <- drm_priors(drm_prior_ridge('mu','x',lambda=0))
  a <- drmTMB(f,data=d,priors=tab)
  b <- drmTMB(f,data=d,priors=con)
  plain <- drmTMB(f,data=d)
  expect_equal(a$opt$objective,b$opt$objective,tolerance=1e-9)
  expect_equal(a$opt$objective,plain$opt$objective,tolerance=1e-8)
  expect_identical(a$estimator,b$estimator)
  expect_equal(a$fixed_prior_penalty,b$fixed_prior_penalty)
  expect_equal(a$resolved_priors,b$resolved_priors)
  expect_identical(profile_targets(a)$profile_ready,profile_targets(b)$profile_ready)
  expect_equal(AIC(a),AIC(b),tolerance=1e-8)
  expect_equal(BIC(a),BIC(b),tolerance=1e-8)
  expect_equal(coef(a),coef(b),tolerance=1e-8)
  db <- data.frame(y=c(0,0,0,1,0,1,1,1),x=c(-3,-2,-1,0,.5,1,2,3))
  fb <- bf(mu=y~x)
  tb <- data.frame(prior=c('ridge(1)','ridge(1)'),class=c('fixef','fixef'),coef=c('(Intercept)','x'))
  cb <- drm_priors(drm_prior_ridge('mu','all',lambda=1,intercept='include'))
  x <- drmTMB(fb,data=db,family=binomial(),priors=tb)
  y <- drmTMB(fb,data=db,family=binomial(),priors=cb)
  expect_equal(x$opt$objective,y$opt$objective,tolerance=1e-8)
  expect_equal(x$opt$par,y$opt$par,tolerance=1e-6)
  expect_equal(x$obj$gr(x$opt$par),y$obj$gr(x$opt$par),tolerance=1e-8)
})

testthat::test_that('table priors preserve constructor inference guards', {
  d <- data.frame(x=rep(c(-1,0,1),6),g=factor(rep(1:6,each=3)))
  d$y <- .5+.6*d$x+rep(c(-.5,.2,.7,-.3,.4,-.4),each=3)+rep(c(.1,-.2,.1),6)
  f <- bf(y~x+(1|g),sigma~1)
  tab <- data.frame(prior='normal(0,0.8)',class='fixef',coef='x')
  con <- drm_priors(drm_prior_normal('mu','x',sd=.8))
  a <- drmTMB(f,data=d,priors=tab); b <- drmTMB(f,data=d,priors=con)
  for (fit in list(a,b)) {
   expect_error(confint(fit),'fixed-effect')
   expect_error(confint(fit,method='bootstrap'),'fixed-effect')
   expect_error(summary(fit,conf.int=TRUE),'fixed-effect')
   expect_error(predict_parameters(fit,conf.int=TRUE),'fixed-effect')
   expect_error(profile(fit),'fixed-effect')
   expect_error(AIC(fit),'fixed-effect')
   expect_error(BIC(fit),'fixed-effect')
   expect_error(drm_lrtest(fit,fit),'MAP')
  }
  expect_equal(a$resolved_priors,b$resolved_priors)
})
