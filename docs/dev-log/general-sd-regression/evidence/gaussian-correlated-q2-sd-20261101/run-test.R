args <- commandArgs(TRUE)
res <- devtools::test(filter = args[1], reporter = "summary", stop_on_failure = FALSE)
df <- as.data.frame(res)
cat("\n=== COUNTS ===\n")
cat("test_blocks:", nrow(df), "\n")
cat("expectations_passed:", sum(df$passed), "\n")
cat("failed:", sum(df$failed), "\n")
cat("errors:", sum(df$error), "\n")
cat("skipped_blocks:", sum(df$skipped), "\n")
cat("warnings:", sum(df$warning), "\n")
print(df[, c("test","nb","passed","failed","skipped","error","warning")])
ok <- sum(df$failed) == 0 && !any(df$error) && !any(df$skipped)
cat("EXIT_STATUS:", if (ok) 0L else 1L, "\n")
quit(status = if (ok) 0L else 1L)
